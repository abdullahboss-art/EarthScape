def norm(s):
    s = unicodedata.normalize("NFKD", str(s)).encode("ascii", "ignore").decode().lower()
    return " ".join(re.sub(r"[^a-z0-9]+", " ", s).split())


NAME2ISO = {norm(v[0]): k for k, v in COUNTRIES.items()}
NAME2ISO.update({norm(a): v for a, v in ALIASES.items()})


def iso3(name):
    """Country ka naam -> ISO-3 code (ya None)."""
    return NAME2ISO.get(norm(name))
